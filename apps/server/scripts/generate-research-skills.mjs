import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

const serverRoot = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "..");
const repoRoot = NodePath.resolve(serverRoot, "..", "..");
const skillsRoot = NodePath.join(repoRoot, ".agents", "skills");
const outputPath = NodePath.join(serverRoot, "src", "research", "researchSkills.generated.ts");
const names = [
  "erebus-adaptive-fuzzing",
  "erebus-chain-discovery",
  "erebus-codebase-research",
  "erebus-evidence-testing",
  "erebus-exploit-validation",
  "erebus-external-intel",
  "erebus-finding-report",
  "erebus-web-research",
];

const definitions = await Promise.all(
  names.map(async (name) => {
    const root = NodePath.join(skillsRoot, name);
    const skill = await NodeFSP.readFile(NodePath.join(root, "SKILL.md"), "utf8");
    const supportingFiles =
      name === "erebus-finding-report"
        ? {
            "references/report-template.md": await NodeFSP.readFile(
              NodePath.join(root, "references", "report-template.md"),
              "utf8",
            ),
          }
        : undefined;
    return { name, skill, ...(supportingFiles ? { supportingFiles } : {}) };
  }),
);

const source = `// Generated by scripts/generate-research-skills.mjs. Do not edit directly.\nexport const MANAGED_RESEARCH_SKILLS = ${JSON.stringify(definitions, null, 2)} as const;\n`;
await NodeFSP.writeFile(outputPath, source, "utf8");
